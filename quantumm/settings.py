# Lightweight .env loader (no external dependency). Real environment variables
# always win, so container/CI configuration takes precedence. Must run before
# any os.environ.get() call below.
# -----------------------------------------------------------------------------
def _load_dotenv(path):
    try:
        if not path.is_file():
            return
        with path.open('r', encoding='utf-8') as handle:
            for raw_line in handle:
                line = raw_line.strip()
                if not line or line.startswith('#') or '=' not in line:
                    continue
                key, _, value = line.partition('=')
                os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))
    except OSError:
        pass


